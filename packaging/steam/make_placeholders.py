#!/usr/bin/env python3
"""The placeholder Steam artwork (game.json launcher.steam_art; psxstack docs/LAUNCHER.md "Steam"): the five
pictures Add to Steam puts beside the shortcut, drawn from the port's own icon (packaging/appimage/dcb.svg: two
cards fanned on a tile, nothing from the game) at Steam's sizes. They are placeholders, labelled so on the pictures
that carry a background (the capsules and the hero), until proper art replaces them (README.txt).

  packaging/steam/make_placeholders.py      # writes the SVG sources and renders the PNGs beside this file (Inkscape)
"""
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ICON = HERE.parent / "appimage" / "dcb.svg"
TITLE = ("Digimon", "Digital Card Battle")
FONT = "Liberation Sans, DejaVu Sans, sans-serif"
LABEL = "placeholder art · the PC port"

DEFS = """<defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#1f6f5c"/>
      <stop offset="1" stop-color="#0d3329"/>
    </linearGradient>
    <linearGradient id="card" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#f4f1e6"/>
      <stop offset="1" stop-color="#cfc8b0"/>
    </linearGradient>
  </defs>"""

# The icon's two cards (dcb.svg without its tile), in its 256-unit box.
CARDS = """<g transform="rotate(-14 128 136)">
      <rect x="62" y="52" width="104" height="148" rx="12" fill="#b9472f" stroke="#f4f1e6" stroke-width="6"/>
      <rect x="80" y="70" width="68" height="112" rx="6" fill="none" stroke="#f4f1e6" stroke-width="4" opacity="0.7"/>
    </g>
    <g transform="rotate(12 128 136)">
      <rect x="96" y="58" width="104" height="148" rx="12" fill="url(#card)" stroke="#0d3329" stroke-width="4"/>
      <path d="M148 98 l20 34 -20 34 -20 -34 z" fill="#1f6f5c"/>
      <circle cx="148" cy="132" r="7" fill="#f4f1e6"/>
    </g>"""


def cards(x, y, size):
    """The cards scaled into a size x size box at (x, y)."""
    return f'<g transform="translate({x} {y}) scale({size / 256})">\n    {CARDS}\n  </g>'


def text(x, y, size, s, anchor="middle", weight="bold", fill="#f4f1e6", opacity=1.0, outline=0):
    stroke = f' stroke="#0d3329" stroke-width="{outline}" paint-order="stroke" stroke-linejoin="round"' if outline else ""
    return (f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" font-weight="{weight}" '
            f'text-anchor="{anchor}" fill="{fill}" opacity="{opacity}"{stroke}>{s}</text>')


def svg(w, h, body, background=True):
    bg = f'<rect width="{w}" height="{h}" fill="url(#bg)"/>' if background else ""
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n'
            f'<!-- Placeholder Steam artwork, {w}x{h}: generated by make_placeholders.py from the port\'s icon '
            f'(packaging/appimage/dcb.svg); nothing from the game. -->\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">\n  {DEFS}\n'
            f'  {bg}\n  {body}\n</svg>\n')


PICTURES = {
    # the library's portrait capsule
    "capsule": svg(600, 900, "\n  ".join([
        cards(100, 120, 400),
        text(300, 640, 64, TITLE[0]),
        text(300, 720, 52, TITLE[1]),
        text(300, 870, 24, LABEL, weight="normal", opacity=0.7),
    ])),
    # the wide capsule
    "wide_capsule": svg(920, 430, "\n  ".join([
        cards(30, 55, 320),
        text(370, 190, 64, TITLE[0], anchor="start"),
        text(370, 260, 50, TITLE[1], anchor="start"),
        text(900, 410, 20, LABEL, anchor="end", weight="normal", opacity=0.7),
    ])),
    # the game page's banner (Steam draws the logo over it, so no title here)
    "hero": svg(3840, 1240, "\n  ".join([
        f'<g opacity="0.35">{cards(160, 140, 960)}</g>',
        f'<g opacity="0.35">{cards(2720, 140, 960)}</g>',
        text(3800, 1200, 40, LABEL, anchor="end", weight="normal", opacity=0.6),
    ])),
    # the logo over the hero: transparent, the title outlined so it reads on any background
    "logo": svg(1280, 720, "\n  ".join([
        text(640, 330, 150, TITLE[0], outline=14),
        text(640, 480, 110, TITLE[1], outline=12),
    ]), background=False),
}


def main():
    inkscape = shutil.which("inkscape")
    if inkscape is None:
        sys.exit("make_placeholders.py: Inkscape is needed to render the PNGs")
    jobs = [(name, HERE / f"{name}.svg") for name in PICTURES]
    for name, path in jobs:
        path.write_text(PICTURES[name])
    jobs.append(("icon", ICON))  # the icon is the port's own, at Steam's 256x256
    for name, src in jobs:
        subprocess.run([inkscape, str(src), "--export-type=png", f"--export-filename={HERE / (name + '.png')}"],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        print(f"{name}.png")


if __name__ == "__main__":
    main()
